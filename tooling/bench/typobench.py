# --- multi-file "modules" family -----------------------------------------
# A project of many small .ts modules that import/export across each other,
# exercising typokat's M29 cross-file pipeline (scan_imports + dependency
# order + cross-universe checking). Globals live in a single script file so
# tsc/tsgo stay happy under --noLib; every module is a real module (has
# import/export), so its own declarations never satisfy the global lookup.

MODULE_STEM = "mod_{:05d}"
MODULE_LINES_PER_MODULE = 16  # rough; used only to size the module count


def module_name(i):
    return MODULE_STEM.format(i)


def module_chunk(i):
    # Each module depends on the two preceding ones (a DAG, not a bare chain),
    # composing their exported types/values so the check must resolve imports.
    deps = [d for d in (i - 1, i - 2) if d >= 0]
    lines = [f'import {{ Shape_{d}, seed_{d} }} from "./{module_name(d)}";' for d in deps]
    left_type = f"Shape_{deps[0]}" if deps else "number"
    right_type = f"Shape_{deps[1]}" if len(deps) > 1 else left_type
    seed_expr = " + ".join([f"seed_{d}" for d in deps] + [str(i)])
    lines += [
        f"export type Shape_{i} = {{",
        "  id: number;",
        "  label: string;",
        f"  left: {left_type};",
        f"  right: {right_type};",
        "};",
        f"export interface Widget_{i} {{",
        f"  shape: Shape_{i};",
        "  weight: number;",
        "}",
        f"export const seed_{i}: number = {seed_expr};",
        f"export function blend_{i}(w: Widget_{i}): number {{ return w.shape.id + w.weight; }}",
        f"export function pick_{i}(s: Shape_{i}): {left_type} {{ return s.left; }}",
        f"const probe_{i}: number = seed_{i};",
        "",
    ]
    return lines


def module_main(n_modules):
    # Fan-in consumer: pull a value from a spread of modules, plus the top type.
    last = n_modules - 1
    step = max(1, n_modules // 16)
    sample = sorted({0, *range(0, n_modules, step)} - {last})
    lines = [f'import {{ seed_{d} }} from "./{module_name(d)}";' for d in sample]
    lines.append(f'import {{ Shape_{last}, pick_{last} }} from "./{module_name(last)}";')
    total = " + ".join(f"seed_{d}" for d in sample)
    lines += [
        f"export const grandTotal: number = {total};",
        f"export function consumeTop(s: Shape_{last}): number {{ return pick_{last}(s).id; }}",
        "",
    ]
    return lines


def module_count_for_size(size):
    reserve = len(GLOBAL_HEADER) + 24  # globals.ts + a generous main.ts budget
    return max(MODULE_MIN_COUNT, (size - reserve) // MODULE_LINES_PER_MODULE)


def module_dir(size):
    return CORPUS / f"modules-{size}"


def module_sort_key(path):
    stem = path.stem
    if stem == "globals":
        return (0, 0)
    if stem == "main":
        return (2, 0)
    return (1, int(stem.split("_")[1]))


def module_project_paths(size):
    directory = module_dir(size)
    if not directory.is_dir():
        return [directory]  # non-existent sentinel; ensure_files_exist reports it
    files = sorted(directory.glob("*.ts"), key=module_sort_key)
    return files or [directory]


def generate_module_project(size):
    directory = module_dir(size)
    shutil.rmtree(directory, ignore_errors=True)
    n = module_count_for_size(size)
    paths = []
    write_lines(directory / "globals.ts", GLOBAL_HEADER)
    paths.append(directory / "globals.ts")
    for i in range(n):
        path = directory / f"{module_name(i)}.ts"
        write_lines(path, module_chunk(i))
        paths.append(path)
    write_lines(directory / "main.ts", module_main(n))
    paths.append(directory / "main.ts")
    return paths


def corpus_path(family, size):
    return CORPUS / f"{family}-{size}.ts"


def generate_files(families, sizes, include_startup=True):
    records = []
    if include_startup:
        path = CORPUS / "startup.ts"
        lines = startup_lines()
        write_lines(path, lines)
        records.append({"family": "startup", "size": len(lines), "path": str(path),
                        "paths": [str(path)], "files": 1, "lines": len(lines)})

    for family in families:
        for size in sizes:
            if family in MODULE_FAMILIES:
                paths = generate_module_project(size)
                lines = total_lines(paths)
                records.append({"family": family, "size": size, "path": str(module_dir(size)),
                                "paths": [str(p) for p in paths], "files": len(paths), "lines": lines})
            else:
                path = corpus_path(family, size)
                lines = GENERATORS[family](size)
                write_lines(path, lines)
                records.append({"family": family, "size": size, "path": str(path),
                                "paths": [str(path)], "files": 1, "lines": len(lines)})

    manifest = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "families": list(families),
        "sizes": list(sizes),
        "files": records,
    }
    CORPUS.mkdir(parents=True, exist_ok=True)
    (CORPUS / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return records


def selected_files(families, sizes, include_startup):
    items = []
    if include_startup:
        items.append(("startup", "startup", [CORPUS / "startup.ts"]))
    for family in families:
        for size in sizes:
            if family in MODULE_FAMILIES:
                items.append((family, size, module_project_paths(size)))
            else:
                items.append((family, size, [corpus_path(family, size)]))
    return items


def ensure_files_exist(items):
    missing = [path for _family, _size, paths in items for path in paths if not path.exists()]
    if missing:
        listed = "\n".join(f"  {p}" for p in missing[:12])
        if len(missing) > 12:
            listed += f"\n  ... +{len(missing) - 12} more"
        sys.exit(f"missing generated corpus files:\n{listed}\nrun `python3 typobench.py generate` first")


def resolve_binary(path_or_name):
    path = Path(path_or_name)
    if path.exists():
        return str(path.resolve())
    found = shutil.which(path_or_name)
    if found:
        return found
    return path_or_name


def command_parts(command):
    parts = shlex.split(str(command))
    if not parts:
        raise ValueError("empty command")
    first = resolve_binary(parts[0])
    return [first, *parts[1:]]


def default_tsgo():
    if LOCAL_TSC.exists():
        return str(LOCAL_TSC)
    if LOCAL_TSGO.exists():
        return str(LOCAL_TSGO)
    return "tsgo"


def build_tool_command(tool, args, paths):
    path_args = [str(p) for p in paths]
    if tool == "typokat":
        command = [*command_parts(args.typokat), "check"]
        if args.typokat_format != "rich":
            command.extend(["--format", args.typokat_format])
        return [*command, *path_args]
    if tool == "tsgo":
        return [*command_parts(args.tsgo), *args.tsgo_flags, *path_args]
    if tool == "tsc":
        return [*command_parts(args.tsc), *args.tsgo_flags, *path_args]
    raise AssertionError(tool)


def ensure_tool_available(tool, args):
    if tool == "typokat":
        parts = command_parts(args.typokat)
    elif tool == "tsgo":
        parts = command_parts(args.tsgo)
    else:
        parts = command_parts(args.tsc)

    binary = parts[0]
    if not Path(binary).exists() and shutil.which(binary) is None:
        hint = ""
        if tool == "tsgo":
            hint = "\nrun `python3 typobench.py setup-tsgo` or pass --tsgo"
        sys.exit(f"{tool} binary not found: {binary}{hint}")


def expects_diagnostics(family):
    return family in ERROR_FAMILIES


def item_display_path(paths):
    if len(paths) == 1:
        return paths[0].relative_to(HERE)
    return paths[0].parent.relative_to(HERE)


def shell_command(argv):
    return " ".join(shlex.quote(str(part)) for part in argv)


def validation_output_excerpt(output_file):
    output_file.seek(0)
    lines = []
    for _ in range(40):
        line = output_file.readline()
        if not line:
            break
        lines.append(line.rstrip("\n"))
    return "\n".join(lines).strip()


def validate_returncode(tool, family, returncode):
    if expects_diagnostics(family):
        if tool == "typokat":
            return returncode == 1
        return returncode != 0
    return returncode == 0


def validation_expectation(tool, family):
    if expects_diagnostics(family):
        if tool == "typokat":
            return "expected typokat diagnostics exit 1"
        return "expected diagnostics exit non-zero"
    return "expected clean exit 0"


def validate_commands(tools, items, args):
    if args.no_validate:
        return
    for family, size, paths in items:
        for tool in tools:
            argv = build_tool_command(tool, args, paths)
            with tempfile.TemporaryFile(mode="w+", encoding="utf-8", errors="replace") as output:
                proc = subprocess.run(
                    argv,
                    cwd=ROOT,
                    stdout=output,
                    stderr=subprocess.STDOUT,
                    timeout=args.validate_timeout,
                )
                if validate_returncode(tool, family, proc.returncode):
                    continue
                label = f"{family}/{size}"
                excerpt = validation_output_excerpt(output)
                detail = validation_expectation(tool, family)
                if excerpt:
                    excerpt = f"\n{excerpt}"
                sys.exit(
                    f"{tool} validation failed for {label} ({item_display_path(paths)}): "
                    f"{detail}, got exit {proc.returncode}{excerpt}"
                )


def run_hyperfine_for_item(tools, family, size, paths, lines, args, raw_dir):
    stem = family if family == "startup" else f"{family}-{size}"
    raw = raw_dir / f"{stem}.json"
    cmd = [
        "hyperfine",
        "--style",
        "basic",
        "--shell",
        args.shell,
        "--warmup",
        str(args.warmup),
        "--runs",
        str(args.runs),
        "--export-json",
        str(raw),
    ]
    if expects_diagnostics(family):
        cmd.append("--ignore-failure")
    commands = []
    for tool in tools:
        argv = build_tool_command(tool, args, paths)
        command = shell_command(argv)
        commands.append((tool, command, argv))
        cmd.extend(["--command-name", tool, command])

    subprocess.run(cmd, cwd=ROOT, check=True)
    data = json.loads(raw.read_text())
    records = []
    for (tool, command, argv), result in zip(commands, data["results"]):
        median = result.get("median", result["mean"])
        mean = result["mean"]
        rss_samples = memory_rss_samples(tool, family, argv, args)
        max_rss_kb = max(rss_samples) if rss_samples else None
        records.append({
            "family": family,
            "size": size,
            "file": str(item_display_path(paths)),
            "files": len(paths),
            "lines": lines,
            "expected": "diagnostics" if expects_diagnostics(family) else "clean",
            "tool": tool,
            "command": command,
            "mean_seconds": mean,
            "median_seconds": median,
            "stddev_seconds": result.get("stddev"),
            "min_seconds": result.get("min"),
            "max_seconds": result.get("max"),
            "lines_per_second": (lines / median) if median else None,
            "max_rss_kb": max_rss_kb,
            "memory_rss_kb_samples": rss_samples,
        })
    return records


def memory_rss_samples(tool, family, argv, args):
    if args.memory_runs <= 0:
        return []
    if not args.memory_tool:
        return []
    samples = []
    for _ in range(args.memory_runs):
        proc = subprocess.run(
            [args.memory_tool, "-v", *argv],
            cwd=ROOT,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            errors="replace",
            timeout=args.memory_timeout,
        )
        output = proc.stdout + proc.stderr
        if not validate_returncode(tool, family, proc.returncode):
            excerpt = "\n".join(output.splitlines()[:40])
            detail = validation_expectation(tool, family)
            if excerpt:
                excerpt = f"\n{excerpt}"
            sys.exit(
                f"{tool} memory run failed for {family}: "
                f"{detail}, got exit {proc.returncode}{excerpt}"
            )
        m = RSS_RE.search(output)
        if not m:
            excerpt = "\n".join(output.splitlines()[-20:])
            sys.exit(f"{tool} memory run did not report max RSS\n{excerpt}")
        samples.append(int(m.group(1)))
    return samples


def write_report(records, tools, families, sizes, args, raw_dir):
    REPORT.mkdir(parents=True, exist_ok=True)
    when = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    has_modules = any(f in MODULE_FAMILIES for f in families)
    mode = "single-file + modules" if has_modules else "single-file"
    caveats = [
        "Single-file families keep most of the corpus inside a per-file scope.",
        "The modules family is multi-file: it exercises typokat's M29 import resolution and cross-file checking, and is the row where tsgo's cross-file parallelism helps most. Read it as the multi-file comparison.",
        "--noEmit disables emit output but tsgo/tsc still carry compiler infrastructure typokat does not.",
        "The errors family intentionally exits with diagnostics; preflight validates that before hyperfine ignores the failure status.",
    ]
    payload = {
        "when": when,
        "mode": mode,
        "tools": list(tools),
        "families": list(families),
        "sizes": list(sizes),
        "runs": args.runs,
        "warmup": args.warmup,
        "memory_runs": args.memory_runs,
        "memory_tool": args.memory_tool,
        "typokat_format": args.typokat_format,
        "raw_report_dir": str(raw_dir.relative_to(HERE)),
        "caveats": caveats,
        "results": records,
    }
    (REPORT / "latest.json").write_text(json.dumps(payload, indent=2) + "\n")

    lines = [
        "# typokat synthetic benchmark",
        "",
        f"- when: {when}",
        f"- mode: {mode}",
        f"- hyperfine: {args.runs} runs, {args.warmup} warmup",
        f"- memory: {args.memory_runs} run(s) via {args.memory_tool or 'disabled'}",
        f"- typokat diagnostics: {args.typokat_format}",
        "",
        "> Caveat: single-file families stay in a per-file scope. The `modules` family",
        "> is multi-file and is the one that exercises cross-file resolution and tsgo's",
        "> cross-file parallelism — read those rows as the multi-file comparison.",
        "",
        "| family | expected | files | lines | tool | median s | mean s | lines/s | max RSS MiB |",
        "|---|---|---:|---:|---|---:|---:|---:|---:|",
    ]
    for rec in records:
        lps = rec["lines_per_second"]
        lps_text = f"{lps:,.0f}" if lps is not None else "-"
        rss = rec.get("max_rss_kb")
        rss_text = f"{rss / 1024:.1f}" if rss is not None else "-"
        lines.append(
            f"| {rec['family']} | {rec['expected']} | {rec.get('files', 1)} | {rec['lines']} | "
            f"{rec['tool']} | {rec['median_seconds']:.6f} | {rec['mean_seconds']:.6f} | "
            f"{lps_text} | {rss_text} |"
        )
    (REPORT / "latest.md").write_text("\n".join(lines) + "\n")
    return payload


def cmd_generate(args):
    records = generate_files(args.families, args.sizes, include_startup=True)
    print(f"generated {len(records)} corpus item(s) in {CORPUS.relative_to(HERE)}")
    for rec in records:
        files = rec.get("files", 1)
        suffix = f"  ({files} files)" if files > 1 else ""
        print(f"  {Path(rec['path']).relative_to(HERE)}  {rec['lines']} lines{suffix}")


def cmd_list(args):
    if not CORPUS.exists():
        sys.exit("no corpus directory; run `python3 typobench.py generate` first")
    files = sorted(CORPUS.glob("*.ts"))
    dirs = sorted(CORPUS.glob("modules-*"))
    if not files and not dirs:
        sys.exit("empty corpus directory; run `python3 typobench.py generate` first")
    for path in files:
        print(f"{path.relative_to(HERE)}\t{line_count(path)}")
    for directory in dirs:
        if not directory.is_dir():
            continue
        members = list(directory.glob("*.ts"))
        print(f"{directory.relative_to(HERE)}/\t{total_lines(members)}\t({len(members)} files)")


def cmd_clean(_args):
    shutil.rmtree(CORPUS, ignore_errors=True)
    shutil.rmtree(REPORT, ignore_errors=True)
    print("removed corpus/ and report/")


def cmd_setup_tsgo(args):
    if shutil.which("npm") is None:
        sys.exit("npm not found in PATH")
    package = args.package
    TOOLS_DIR.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["npm", "install", "--prefix", str(TOOLS_DIR), "--no-save", package],
        check=True,
        cwd=HERE,
    )
    binary = LOCAL_TSC if LOCAL_TSC.exists() else LOCAL_TSGO
    if not binary.exists():
        sys.exit(f"install completed, but neither {LOCAL_TSC} nor {LOCAL_TSGO} exists")
    proc = subprocess.run([str(binary), "--version"], capture_output=True, text=True)
    version = (proc.stdout + proc.stderr).strip().splitlines()
    version_text = version[0] if version else "version unknown"
    print(f"installed {package}")
    print(f"tsgo: {binary.relative_to(HERE)} ({version_text})")


def cmd_run(args):
    if shutil.which("hyperfine") is None:
        sys.exit("hyperfine not found in PATH")
    tools = args.tools
    for tool in tools:
        ensure_tool_available(tool, args)
    if args.memory_runs < 0:
        sys.exit("--memory-runs must be >= 0")
    if args.memory_runs > 0:
        args.memory_tool = resolve_binary(args.memory_tool)
        if not Path(args.memory_tool).exists() and shutil.which(args.memory_tool) is None:
            sys.exit(f"memory tool not found: {args.memory_tool}")
    else:
        args.memory_tool = None

    if args.generate:
        generate_files(args.families, args.sizes, include_startup=True)

    items = selected_files(args.families, args.sizes, args.include_startup)
    ensure_files_exist(items)

    validate_commands(tools, items, args)

    stamp = time.strftime("%Y%m%d-%H%M%S")
    raw_dir = RAW_REPORT / stamp
    raw_dir.mkdir(parents=True, exist_ok=True)

    records = []
    for family, size, paths in items:
        lines = total_lines(paths)
        label = family if family == "startup" else f"{family}/{size}"
        files_note = f", {len(paths)} files" if len(paths) > 1 else ""
        print(f"\n== {label}: {item_display_path(paths)} ({lines} lines{files_note}) ==", flush=True)
        records.extend(run_hyperfine_for_item(tools, family, size, paths, lines, args, raw_dir))

    write_report(records, tools, args.families, args.sizes, args, raw_dir)
    print(f"\nwrote {REPORT.relative_to(HERE)}/latest.json")
    print(f"wrote {REPORT.relative_to(HERE)}/latest.md")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="cmd", required=True)

    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--families", type=parse_families, default=FAMILIES,
                        help="comma-separated corpus families, or 'all' (default)")
    common.add_argument("--sizes", type=parse_sizes, default=DEFAULT_SIZES,
                        help="comma-separated line counts (default: 1000,10000,100000)")

    p_gen = sub.add_parser("generate", parents=[common], help="generate synthetic TS corpus")
    p_gen.set_defaults(func=cmd_generate)

    p_list = sub.add_parser("list", help="list generated corpus files")
    p_list.set_defaults(func=cmd_list)

    p_clean = sub.add_parser("clean", help="remove generated corpus and reports")
    p_clean.set_defaults(func=cmd_clean)

    p_setup = sub.add_parser("setup-tsgo", help=f"install {TSGO_PACKAGE} into .tools/")
    p_setup.add_argument("--package", default=TSGO_PACKAGE,
                         help=f"npm package spec to install (default: {TSGO_PACKAGE})")
    p_setup.set_defaults(func=cmd_setup_tsgo)

    p_run = sub.add_parser("run", parents=[common], help="run hyperfine over selected corpus")
    p_run.add_argument("--tools", type=parse_tools, default=DEFAULT_TOOLS,
                       help="comma-separated tools: typokat,tsgo,tsc (default: typokat,tsgo)")
    p_run.add_argument("--typokat", default=str(ROOT / "target/release/typokat"),
                       help="path to typokat binary")
    p_run.add_argument("--typokat-format", choices=("rich", "compact"), default="rich",
                       help="diagnostic renderer for typokat (default: rich)")
    p_run.add_argument("--tsgo", default=default_tsgo(),
                       help="path/name/command for tsgo (default: .tools tsc/tsgo if installed, else PATH)")
    p_run.add_argument("--tsc", default="tsc", help="path/name of tsc binary")
    p_run.add_argument("--tsgo-flags", type=lambda s: parse_csv(s), default=TSGO_FLAGS,
                       help="comma-separated flags for tsgo/tsc (default: --noEmit,--noLib,--skipLibCheck)")
    p_run.add_argument("--runs", type=int, default=10, help="hyperfine runs per command")
    p_run.add_argument("--warmup", type=int, default=0, help="hyperfine warmup runs")
    p_run.add_argument("--memory-runs", type=int, default=1,
                       help="peak-RSS samples per command via /usr/bin/time -v (default: 1; 0 disables)")
    p_run.add_argument("--memory-tool", default="/usr/bin/time",
                       help="GNU time-compatible binary for memory measurement (default: /usr/bin/time)")
    p_run.add_argument("--memory-timeout", type=int, default=1800,
                       help="seconds per memory sample command (default: 1800)")
    p_run.add_argument("--shell", default="none",
                       help="hyperfine shell mode (default: none, so shell startup is not counted)")
    p_run.add_argument("--generate", action=argparse.BooleanOptionalAction, default=True,
                       help="generate selected corpus before running (default: true)")
    p_run.add_argument("--include-startup", action=argparse.BooleanOptionalAction, default=True,
                       help="include startup.ts cold-start floor (default: true)")
    p_run.add_argument("--no-validate", action="store_true",
                       help="skip one-shot preflight validation for each tool/file")
    p_run.add_argument("--validate-timeout", type=int, default=120,
                       help="seconds per one-shot validation command")
    p_run.set_defaults(func=cmd_run)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()

def parse_csv(value, allowed=None, cast=str):
    parts = [p for p in re.split(r"[,\s]+", value.strip()) if p]
    out = []
    for part in parts:
        item = cast(part)
        if allowed is not None and item not in allowed:
            valid = ", ".join(allowed)
            raise argparse.ArgumentTypeError(f"unknown value {part!r}; expected one of: {valid}")
        out.append(item)
    return tuple(out)


def parse_sizes(value):
    sizes = parse_csv(value, cast=int)
    for size in sizes:
        if size < len(GLOBAL_HEADER) + 2:
            raise argparse.ArgumentTypeError(f"size {size} is too small")
    return sizes


def parse_families(value):
    if value.strip() == "all":
        return FAMILIES
    return parse_csv(value, allowed=FAMILIES)


def parse_tools(value):
    return parse_csv(value, allowed=("typokat", "tsgo", "tsc"))


def write_lines(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def line_count(path):
    with path.open() as f:
        return sum(1 for _ in f)


def total_lines(paths):
    return sum(line_count(p) for p in paths)


def pad_to(lines, target, family):
    if len(lines) > target:
        raise RuntimeError(f"{family} generator overshot target: {len(lines)} > {target}")
    i = 0
    while len(lines) < target:
        lines.append(f"type __{family}_pad_{i} = number;")
        i += 1


def append_if_fits(lines, chunk, target):
    if len(lines) + len(chunk) <= target:
        lines.extend(chunk)
        return True
    return False


def wide_props(count, value_type):
    return [f"  p{idx:02d}: {value_type(idx)};" for idx in range(count)]


def relation_chunk(i):
    prop_count = 24
    target = [
        f"type RelTarget_{i} = {{",
        *wide_props(prop_count, lambda idx: "number" if idx % 3 == 0 else ("string" if idx % 3 == 1 else "boolean")),
        f"  tag: \"rel_{i}\";",
        "};",
    ]
    source = [
        f"type RelSource_{i} = {{",
        *wide_props(prop_count, lambda idx: "number" if idx % 3 == 0 else ("string" if idx % 3 == 1 else "boolean")),
        f"  tag: \"rel_{i}\";",
        "  extra0: number;",
        "  extra1: string;",
        "};",
    ]
    union_members = [f"RelTarget_{j}" for j in range(max(0, i - 4), i + 1)]
    union = " | ".join(union_members)
    return [
        *target,
        *source,
        f"type RelUnion_{i} = {union};",
        f"declare const rel_src_{i}: RelSource_{i};",
        f"const rel_assign_{i}_a: RelTarget_{i} = rel_src_{i};",
        f"const rel_assign_{i}_b: RelTarget_{i} = rel_src_{i};",
        f"const rel_union_{i}: RelUnion_{i} = rel_src_{i};",
        f"const rel_prop_{i}: string = rel_src_{i}.p01;",
        "",
    ]


def generate_relation(target):
    lines = [*GLOBAL_HEADER]
    i = 0
    while append_if_fits(lines, relation_chunk(i), target):
        i += 1
    pad_to(lines, target, "relation")
    return lines


